#!/usr/bin/env node
// The generated documents of version 5 (work package 11). Nothing in them is written by hand: each
// table comes from the code or data that decides the behaviour, so a document cannot drift from it.
//
//   node packages/docs/generate.mjs [--root <repository folder>]           write the documents
//   node packages/docs/generate.mjs --check [--root <repository folder>]   exit 1 when one is stale
//
// Outputs (relative to the root):
//   docs/RECIPE.md          the recipe of record, from recipe/RECIPE.json (where ROADMAP WP 11 puts it)
//   docs/v5/REFERENCE.md    commands (from the CLI itself), health states and their fixes (from
//                           packages/health: FIX, assess, renderLine), what runs, writes and sends
//   docs/v5/PARITY.md       every 4.7.28 capability and its fate, from packages/docs/parity.json
// No clock time and no machine path is written, so the same tree always gives the same bytes.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const at = args.indexOf('--root');
const ROOT = at >= 0 ? path.resolve(args[at + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const rel = (...p) => path.join(ROOT, ...p);
const load = (...p) => import(pathToFileURL(rel(...p)).href);
const readJson = (...p) => JSON.parse(fs.readFileSync(rel(...p), 'utf8'));
const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');
const banner = (from) => `<!-- Generated by packages/docs/generate.mjs from ${from}. Do not edit: change the source and run \`node packages/docs/generate.mjs\`; \`--check\` fails when this file is stale. -->`;

export class Stale extends Error {}

function recipeDoc() {
  const text = fs.readFileSync(rel('recipe', 'RECIPE.json'), 'utf8');
  const r = JSON.parse(text);
  const p = r.units.passage;
  const out = [banner('recipe/RECIPE.json'), '', `# The recipe of record: ${r.id}`, ''];
  out.push(`Recipe version ${r.version}, sha256 \`${crypto.createHash('sha256').update(text).digest('hex')}\`. This file is the only place that says how knowledge is cut, indexed and searched; the builder and the engine both load it, and every pack carries a copy.`, '');
  out.push('## Units', '', table(['Setting', 'Value'], [
    ['passage outer bounds', `${p.chunker.name} v${p.chunker.version}: at most ${p.chunker.maxLines} lines, ${p.chunker.maxChars} characters`],
    ['passage chunker', `${p.symbolChunker.name} v${p.symbolChunker.version}: at most ${p.symbolChunker.maxTokens} estimated tokens, grouped toward ${p.symbolChunker.groupTarget}`],
    ['passage header', p.header],
    ['history kinds', r.units.history.kinds.join(', ')],
    ['history standing', Object.entries(r.units.history.standing).map(([k, v]) => `${k} ${v}`).join(', ')],
    ['history split', `${r.units.history.splitChars} characters`],
  ]), '');
  out.push('## Sources', '', table(['Setting', 'Value'], [
    ['file types read', r.sources.include.join(' ')],
    ['folders skipped', r.sources.excludeDirs.join(' ')],
    ['largest file read', `${r.sources.maxFileBytes} bytes`],
    ['standing', `docs ${r.standing.doc}, code ${r.standing.code}${Object.entries(r.standing.byKind ?? {}).map(([k, v]) => `, ${k} ${v}`).join('')}`],
    ['secret screen', r.screen.secrets.map((s) => s.rule).join(', ')],
    ['hostile-text screen', r.screen.hostile.map((s) => s.rule).join(', ')],
    ['unreadable sources carried', `at most ${r.carry.maxShare * 100}% of sources`],
  ]), '');
  const a = r.analyser;
  out.push('## Keyword analyser', '', table(['Setting', 'Value'], [
    ['name', a.name], ['full-text tokenizer', a.fts5Tokenizer], ['stemmer', a.stemmer], ['split identifiers', String(a.splitIdentifiers)],
    ['shortest token', a.minTokenLength], ['shortest number', a.minNumberLength], ['stopwords', a.stopwords.length],
  ]), '');
  out.push('## Models', '', r.models.length ? table(['Name', 'Revision'], r.models.map((m) => [m.name, m.revision])) : 'None: day one searches with keywords and history only.', '');
  out.push('## Lanes', '', table(['Lane', 'Kind', 'Required', 'Pack file role', 'Weights (subject, body)', 'Depth', 'Unit'], r.lanes.map((l) => [l.name, l.kind, l.optional ? 'no' : 'yes', l.role, `${l.weights?.subject}, ${l.weights?.body}`, l.depth, l.unit])), '');
  out.push('## Result', '', table(['Section', 'Lane', 'Items', 'Characters per item', 'Budget brief', 'Budget full'], r.sections.map((s) => [s.name, s.lane, s.maxItems, s.itemChars, s.budgetChars.brief, s.budgetChars.full])), '');
  out.push(table(['Setting', 'Value'], [
    ['whole result cap', `brief ${r.result.capChars.brief}, full ${r.result.capChars.full} characters`],
    ['default detail', r.result.defaultDetail],
    ['delivery ceiling', r.result.delivery ? `${r.result.delivery.maxChars} characters, ${r.result.delivery.maxTokens} tokens` : 'none named'],
    ['search deadline', `${r.deadlineMs} ms`],
    ['probes', `${r.probes.perRepo} per repository, ${r.probes.termsPerProbe} terms each`],
  ]), '');
  return out.join('\n');
}

async function healthRows() {
  const { assess, FIX } = await load('packages', 'health', 'assess.mjs');
  const { renderLine } = await load('packages', 'health', 'line.mjs');
  const now = Date.UTC(2026, 0, 1);
  const s = { pid: 1, alive: true, startedAt: now - 5000, heartbeatAt: now - 1000, knowledgeDate: '2026-11-16', lanes: [{ name: 'lexical', available: true }], probe: { ok: true, at: now - 2000, results: [{ pass: true, expect: 'alpha-vectors/README.md' }] }, lastSearch: null, app: '5.0.0', pack: 'g1' };
  const ev = (servers, extra = {}) => ({ now, installed: true, servers, staleAfterMs: 180_000, probeIntervalMs: 30 * 60_000, ...extra });
  const cases = [
    ['ok', ev([s])],
    ['not-installed', ev([], { installed: false })],
    ['not-running', ev([])],
    ['heartbeat', ev([{ ...s, heartbeatAt: now - 10 * 60_000 }])],
    ['pending', ev([{ ...s, probe: null }])],
    ['probe-failed', ev([{ ...s, probe: { ok: false, at: now - 2000, error: 'a probe did not find its file' } }])],
    ['no-probes', ev([{ ...s, probe: { ok: true, at: now - 2000, results: [] } }])],
    ['incomplete', ev([{ ...s, probe: { ok: true, results: [{}] } }])],
    ['overdue', ev([{ ...s, probe: { ...s.probe, at: now - 2 * 3_600_000 } }])],
    ['generation', ev([s], { pointer: { app: '5.0.1', pack: 'g2' } })],
    ['lane', ev([{ ...s, lanes: [{ name: 'history', available: false }] }])],
    ['safe-mode', ev([{ ...s, lastSearch: { ok: false, at: now - 1000, reason: 'the deadline passed' } }])],
    ['rolled-back', ev([s], { update: { rolledBack: true, at: now - 1000, to: { app: '5.0.2' } } })],
    ['host-unserved', ev([s], { unserved: [{ host: 'Codex', why: 'a [mcp_servers.ruvnet-brain-5] table outside the managed block' }] })],
  ];
  const missing = Object.keys(FIX).filter((k) => !cases.some(([c]) => c === k));
  if (missing.length) throw new Stale(`packages/health has causes this generator does not describe: ${missing.join(', ')}; add a case for each`);
  return cases.map(([cause, e]) => {
    const v = assess(e);
    if ((v.cause ?? 'ok') !== cause && !(cause === 'ok' && v.cause === null)) throw new Stale(`the ${cause} evidence gave cause ${v.cause}`);
    return [cause, v.label, v.fix ?? '(none)', renderLine({ ...v, since: null })];
  });
}

function cliOut(argv) {
  const home = path.join(os.tmpdir(), 'rb5-docs-nonexistent-home');
  const r = spawnSync(process.execPath, [rel('packages', 'cli', 'ruvnet-brain.mjs'), ...argv], { encoding: 'utf8', env: { ...process.env, RUVNET_BRAIN5_HOME: home }, timeout: 30_000 });
  return `${r.stdout}${r.stderr}`.trim();
}

async function referenceDoc() {
  const version = readJson('packages', 'version.json').app;
  const { DEFAULTS } = await load('packages', 'contract', 'constants.mjs');
  const { paths } = await load('packages', 'contract', 'home.mjs');
  const { SHIM_PLAN, HOSTS_FLAG } = await load('packages', 'cli', 'hosts.mjs');
  const { WRITES } = await load('packages', 'migrate', 'brake.mjs');
  const { OVERRIDE_LOG } = await load('packages', 'guard', 'guard.mjs');
  const { SERVER } = await load('packages', 'plugin', 'install.mjs');
  const { BACKUP_DIR } = await load('packages', 'plugin', 'host-backup.mjs');
  const hooks = readJson('packages', 'plugin', 'claude', 'hooks', 'hooks.json').hooks;
  const mcp = readJson('packages', 'plugin', 'claude', '.mcp.json');
  const out = [banner('the CLI, packages/health, packages/contract and packages/plugin'), '', `# RuvNet Brain ${version}: reference`, ''];
  out.push('## Commands', '', 'As printed by the command itself (`ruvnet-brain` with no arguments, then each added command with `--help`).', '');
  out.push('```', cliOut([]), cliOut(['migrate', '--help']), cliOut(['guard', '--help']), '```', '');
  out.push('## Health states and their fixes', '', 'Every state the one verdict can produce, from `packages/health/assess.mjs` (`FIX`, `assess`) and `packages/health/line.mjs` (`renderLine`); the live line also shows "since <time>".', '');
  out.push(table(['Cause', 'State', 'Fix', 'Line the AI sees'], (await healthRows()).map(([c, l, f, line]) => [c, l, `\`${f}\``, `\`${line}\``])), '');
  out.push('## What runs, what is written, what is sent', '', 'From `packages/plugin/claude` (the host entries; an installed copy names the launcher under the brain home in place of `${CLAUDE_PLUGIN_ROOT}`), `packages/contract` (defaults and the home layout), `packages/cli/hosts.mjs`, `packages/migrate` and `packages/guard`.', '');
  const timers = [['heartbeat', DEFAULTS.heartbeatMs], ['self-test (probes)', DEFAULTS.probeIntervalMs], ['update check', DEFAULTS.updateIntervalMs]];
  out.push(table(['What runs', 'When', 'Detail'], [
    ...Object.entries(hooks).flatMap(([event, groups]) => groups.flatMap((g) => g.hooks.map((h) => [`host hook (${event})`, g.matcher ? `before each ${g.matcher.split('|').join(', ')} (Claude Code only); does nothing while the guard is off` : 'every prompt', `\`${h.command}\`, timeout ${h.timeout} s`]))),
    ...Object.entries(mcp.mcpServers ?? {}).map(([name, sv]) => [`search server "${name}"`, 'one per session, started by the host', `\`${[sv.command, ...(sv.args ?? [])].join(' ')}\``]),
    ...timers.map(([what, ms]) => [`${what}, inside the search server`, `every ${ms / 60_000} min`, 'no scheduled job, cron entry or Windows task']),
  ]), '');
  out.push(table(['What is written', 'Where'], [
    ...Object.entries(paths('<brain home>')).map(([k, v]) => [k, `\`${v.split(path.sep).join('/')}\``]),
    ...SHIM_PLAN.write.map((w) => ['host shim', `\`<brain home>/${w}\``]),
    ...Object.entries(WRITES).map(([k, w]) => [`migrate and rollback-to-4: ${k}`, `\`<brain home>/${w}\` (nothing of 4.7 is written)`]),
    ['write guard override record (only when an override line is used)', `\`<brain home>/${OVERRIDE_LOG}\``],
    ['host settings', `only with \`${HOSTS_FLAG}\`: one prompt hook and one search server ("${SERVER}") per host, plus the write guard's tool-use hook in Claude Code; recorded in state/hosts.json and removed by uninstall`],
    ['pre-registration copies of the host files', `\`<brain home>/${BACKUP_DIR}\` (mode 0600; uninstall puts each file back byte for byte while it is still what registration wrote)`],
  ]), '');
  out.push(table(['What is sent', 'Default', 'Detail'], [
    ['automatic update check', DEFAULTS.autoUpdate ? 'on' : 'off', DEFAULTS.updateUrl ? `to ${DEFAULTS.updateUrl}` : 'no request until an update address is set (install from a web address, or ruvnet-brain config update-url)'],
    ['owner page', DEFAULTS.pageTopic ? 'on' : 'off', 'a POST to the topic in state/config.json pageTopic, only when one is set'],
    ['questions, answers, telemetry', 'none', 'nothing else leaves the machine'],
  ]), '');
  out.push(`Optional write guard: ${DEFAULTS.guard === true ? 'on' : 'off'} by default (\`ruvnet-brain guard on\` turns it on).`, '');
  return out.join('\n');
}

export function checkParity(p) {
  const bad = [];
  const DEC = ['kept', 'replaced', 'dropped', 'undecided'];
  p.rows.forEach((r, i) => {
    const at = `row ${i + 1} (${r.capability ?? 'no capability'})`;
    if (!r.section || !r.capability || !r.roadmap) bad.push(`${at}: section, capability and roadmap are required`);
    if (!DEC.includes(r.decision)) bad.push(`${at}: decision must be one of ${DEC.join(', ')}`);
    if (r.decision === 'kept' && !r.v5) bad.push(`${at}: a kept row says what version 5 has (v5)`);
    if (r.decision === 'replaced' && !r.by) bad.push(`${at}: a replaced row says by what (by)`);
    if ((r.decision === 'dropped' || r.decision === 'undecided') && !r.because) bad.push(`${at}: a ${r.decision} row says why (because)`);
    if (r.decision !== 'dropped' && r.decision !== 'undecided' && !['yes', 'partial', 'no'].includes(r.built)) bad.push(`${at}: built must be yes, partial or no`);
    for (const e of r.evidence ?? []) if (!fs.existsSync(rel(e))) bad.push(`${at}: evidence ${e} does not exist`);
  });
  if (bad.length) throw new Stale(`packages/docs/parity.json is refused:\n  ${bad.join('\n  ')}`);
}

function parityDoc() {
  const p = readJson('packages', 'docs', 'parity.json');
  checkParity(p);
  const count = (d) => p.rows.filter((r) => r.decision === d).length;
  const out = [banner('packages/docs/parity.json'), '', '# Parity: every user-visible capability of 4.7.28 in version 5', ''];
  out.push(`Source: ${p.source}. ${p.rows.length} capabilities: **${count('kept')} kept**, **${count('replaced')} replaced**, **${count('dropped')} dropped** (moved out of the product or stopped), **${count('undecided')} undecided**. ${p.rows.filter((r) => r.owner).length} rows are product-scope decisions for the owner to confirm (marked "owner").`, '');
  for (const section of [...new Set(p.rows.map((r) => r.section))]) {
    out.push(`## ${section}`, '');
    out.push(table(['4.7.28 capability', 'Roadmap', 'Version 5', 'Built'], p.rows.filter((r) => r.section === section).map((r) => [
      r.capability + (r.owner ? ' (owner)' : ''),
      r.roadmap,
      r.decision === 'kept' ? `kept: ${r.v5}` : r.decision === 'replaced' ? `replaced by ${r.by}` : `${r.decision}, because ${r.because}`,
      r.built ?? 'n/a',
    ])), '');
  }
  return out.join('\n');
}

export async function documents() {
  return { 'docs/RECIPE.md': recipeDoc(), 'docs/v5/REFERENCE.md': await referenceDoc(), 'docs/v5/PARITY.md': parityDoc() };
}

async function main() {
  const docs = await documents();
  if (args.includes('--check')) {
    // Line endings are not content: a checkout that turns \n into \r\n is not stale.
    const stale = Object.entries(docs).filter(([f, text]) => !fs.existsSync(rel(f)) || fs.readFileSync(rel(f), 'utf8').replace(/\r\n/g, '\n') !== text).map(([f]) => f);
    if (stale.length) {
      console.error(`stale generated document(s): ${stale.join(', ')}. Run: node packages/docs/generate.mjs`);
      return 1;
    }
    console.log(`${Object.keys(docs).length} generated documents are current`);
    return 0;
  }
  for (const [f, text] of Object.entries(docs)) {
    fs.mkdirSync(path.dirname(rel(f)), { recursive: true });
    fs.writeFileSync(rel(f), text);
    console.log(`wrote ${f}`);
  }
  return 0;
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  try {
    process.exitCode = await main();
  } catch (e) {
    console.error(e instanceof Stale ? e.message : e.stack);
    process.exitCode = 1;
  }
}
